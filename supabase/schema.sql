create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'employee',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint profiles_role_check check (role in ('admin', 'employee'))
);

create table if not exists public.vehicle_types (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(10, 2) not null,
  icon_name text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint vehicle_types_price_non_negative check (price >= 0)
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  vehicle_type_id bigint not null references public.vehicle_types(id),
  vehicle_name text,
  plate_number text,
  price numeric(10, 2) not null,
  employee_id uuid not null references public.profiles(id),
  notes text,
  created_at timestamptz not null default now(),
  constraint sales_price_non_negative check (price >= 0)
);

