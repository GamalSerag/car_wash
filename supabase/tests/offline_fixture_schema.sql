create role anon;
create role authenticated;
create role service_role bypassrls;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$
 select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;
$$;
grant usage on schema auth,public to authenticated,anon,service_role;
create table public.companies(id uuid primary key default gen_random_uuid(),name text not null,is_active boolean not null default true);
create table public.profiles(id uuid primary key,company_id uuid references public.companies(id),full_name text not null,
 role text not null default 'employee',is_active boolean not null default true,created_at timestamptz not null default now());
create table public.vehicle_types(id bigint generated by default as identity primary key,company_id uuid references public.companies(id),
 name text not null,price numeric(10,2) not null,is_active boolean not null default true);
create table public.sales(id bigint generated by default as identity primary key,company_id uuid not null references public.companies(id),
 employee_id uuid not null references public.profiles(id),vehicle_type_id bigint not null references public.vehicle_types(id),
 vehicle_name text,plate_number text,notes text,price numeric(10,2) not null,created_at timestamptz not null default now());
create table public.device_tokens(token text primary key,user_id uuid references public.profiles(id),company_id uuid references public.companies(id),
 platform text not null default 'android',updated_at timestamptz not null default now());
create function public.current_company_id() returns uuid language sql stable security definer set search_path='' as $$
 select p.company_id from public.profiles p join public.companies c on p.company_id=c.id where p.id=auth.uid() and p.is_active and c.is_active;
$$;
create function public.is_company_active(target_company_id uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.companies where id=target_company_id and is_active);
$$;
create function public.is_active_user() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles p join public.companies c on p.company_id=c.id where p.id=auth.uid() and p.is_active and c.is_active);
$$;
create function public.is_company_admin(target_company_id uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles where id=auth.uid() and is_active and
 (role='super_admin' or(role='admin' and company_id=target_company_id and public.is_company_active(company_id))));
$$;
grant insert,select,update,delete on public.sales to authenticated;
grant usage,select on all sequences in schema public to authenticated;
