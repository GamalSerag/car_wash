-- Carpet orders feature for the car wash app.
--
-- How to run:
-- 1. Open Supabase Dashboard > SQL Editor.
-- 2. Paste and run this whole file.
--
-- Flutter uses only the anon/publishable key. Keep service role keys out of
-- the app.

create table if not exists public.carpet_orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone_number text not null,
  total_price numeric(10,2) not null,
  paid_amount numeric(10,2) not null default 0,
  remaining_amount numeric(10,2) not null default 0,
  employee_id uuid not null references public.profiles(id),
  notes text,
  is_delivered boolean not null default false,
  created_at timestamptz not null default now(),
  delivered_at timestamptz
);

create table if not exists public.carpet_order_photos (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.carpet_orders(id) on delete cascade,
  photo_url text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);

alter table public.carpet_orders
drop constraint if exists carpet_orders_total_price_check;

alter table public.carpet_orders
add constraint carpet_orders_total_price_check check (total_price >= 0);

alter table public.carpet_orders
drop constraint if exists carpet_orders_paid_amount_check;

alter table public.carpet_orders
add constraint carpet_orders_paid_amount_check check (paid_amount >= 0);

alter table public.carpet_orders
drop constraint if exists carpet_orders_remaining_amount_check;

alter table public.carpet_orders
add constraint carpet_orders_remaining_amount_check check (remaining_amount >= 0);

create index if not exists carpet_orders_employee_id_idx
on public.carpet_orders(employee_id);

create index if not exists carpet_orders_created_at_idx
on public.carpet_orders(created_at desc);

create index if not exists carpet_order_photos_order_id_idx
on public.carpet_order_photos(order_id);

insert into storage.buckets (id, name, public)
values ('carpet-orders', 'carpet-orders', true)
on conflict (id) do update
set public = true;

alter table public.carpet_orders enable row level security;
alter table public.carpet_order_photos enable row level security;

grant select, insert, update, delete on public.carpet_orders to authenticated;
grant select, insert, update, delete on public.carpet_order_photos to authenticated;
grant usage, select on sequence public.carpet_orders_id_seq to authenticated;
grant usage, select on sequence public.carpet_order_photos_id_seq to authenticated;

drop policy if exists "Active users can insert own carpet orders"
on public.carpet_orders;

drop policy if exists "Employees can read own carpet orders"
on public.carpet_orders;

drop policy if exists "Employees can update own carpet orders"
on public.carpet_orders;

drop policy if exists "Admins can read all carpet orders"
on public.carpet_orders;

drop policy if exists "Admins can update carpet orders"
on public.carpet_orders;

drop policy if exists "Admins can delete carpet orders"
on public.carpet_orders;

drop policy if exists "Users can read carpet order photos"
on public.carpet_order_photos;

drop policy if exists "Users can insert photos for own carpet orders"
on public.carpet_order_photos;

drop policy if exists "Admins can delete carpet order photos"
on public.carpet_order_photos;

drop policy if exists "Users can read carpet photos"
on storage.objects;

drop policy if exists "Users can upload carpet photos"
on storage.objects;

drop policy if exists "Admins can delete carpet photos"
on storage.objects;

create policy "Active users can insert own carpet orders"
on public.carpet_orders
for insert
to authenticated
with check (
  public.is_active_user()
  and employee_id = auth.uid()
);

create policy "Employees can read own carpet orders"
on public.carpet_orders
for select
to authenticated
using (
  public.is_active_user()
  and employee_id = auth.uid()
);

create policy "Employees can update own carpet orders"
on public.carpet_orders
for update
to authenticated
using (
  public.is_active_user()
  and employee_id = auth.uid()
)
with check (
  public.is_active_user()
  and employee_id = auth.uid()
);

create policy "Admins can read all carpet orders"
on public.carpet_orders
for select
to authenticated
using (public.is_admin());

create policy "Admins can update carpet orders"
on public.carpet_orders
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

create policy "Admins can delete carpet orders"
on public.carpet_orders
for delete
to authenticated
using (public.is_admin());

create policy "Users can read carpet order photos"
on public.carpet_order_photos
for select
to authenticated
using (
  exists (
    select 1
    from public.carpet_orders
    where carpet_orders.id = carpet_order_photos.order_id
  )
);

create policy "Users can insert photos for own carpet orders"
on public.carpet_order_photos
for insert
to authenticated
with check (
  exists (
    select 1
    from public.carpet_orders
    where carpet_orders.id = carpet_order_photos.order_id
      and (
        carpet_orders.employee_id = auth.uid()
        or public.is_admin()
      )
  )
);

create policy "Admins can delete carpet order photos"
on public.carpet_order_photos
for delete
to authenticated
using (public.is_admin());

create policy "Users can read carpet photos"
on storage.objects
for select
to authenticated
using (bucket_id = 'carpet-orders');

create policy "Users can upload carpet photos"
on storage.objects
for insert
to authenticated
with check (bucket_id = 'carpet-orders' and public.is_active_user());

create policy "Admins can delete carpet photos"
on storage.objects
for delete
to authenticated
using (bucket_id = 'carpet-orders' and public.is_admin());
