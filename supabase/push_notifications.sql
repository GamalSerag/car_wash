-- Push notifications setup for Firebase Cloud Messaging device tokens.
--
-- How to run:
-- 1. Open your Supabase project dashboard.
-- 2. Go to SQL Editor.
-- 3. Paste this whole file and click Run.
--
-- Important:
-- Do not put Firebase server keys or service-account JSON in Flutter.
-- Server credentials belong only in a trusted backend, such as a Supabase
-- Edge Function, when you are ready to send automatic notifications.

create table if not exists public.device_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  token text not null unique,
  platform text not null default 'android',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists device_tokens_user_id_idx
on public.device_tokens(user_id);

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
      and is_active = true
  );
$$;

alter table public.device_tokens enable row level security;

grant select, insert, update, delete on public.device_tokens to authenticated;
grant usage, select on sequence public.device_tokens_id_seq to authenticated;

drop policy if exists "Users can read their own device tokens"
on public.device_tokens;

drop policy if exists "Users can insert their own device tokens"
on public.device_tokens;

drop policy if exists "Users can update their own device tokens"
on public.device_tokens;

drop policy if exists "Users can delete their own device tokens"
on public.device_tokens;

drop policy if exists "Admins can read all device tokens"
on public.device_tokens;

create policy "Users can read their own device tokens"
on public.device_tokens
for select
to authenticated
using (user_id = auth.uid());

create policy "Users can insert their own device tokens"
on public.device_tokens
for insert
to authenticated
with check (user_id = auth.uid());

create policy "Users can update their own device tokens"
on public.device_tokens
for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create policy "Users can delete their own device tokens"
on public.device_tokens
for delete
to authenticated
using (user_id = auth.uid());

create policy "Admins can read all device tokens"
on public.device_tokens
for select
to authenticated
using (public.is_admin());
