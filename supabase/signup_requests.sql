-- Signup requests for the SaaS flow.
--
-- How to run:
-- 1. Open Supabase Dashboard > SQL Editor.
-- 2. Paste and run this whole file after saas_multitenancy.sql.
-- 3. Deploy the create-company-user Edge Function before creating users
--    from the Flutter super-admin screen.

create table if not exists public.signup_requests (
  id bigint generated by default as identity primary key,
  company_name text not null,
  owner_name text not null,
  phone text not null,
  email text not null,
  address text,
  notes text,
  status text not null default 'pending',
  company_id uuid references public.companies(id),
  approved_by uuid references public.profiles(id),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  constraint signup_requests_status_check
    check (status in ('pending', 'approved', 'rejected'))
);

create index if not exists signup_requests_status_created_at_idx
on public.signup_requests(status, created_at desc);

alter table public.signup_requests enable row level security;

grant insert on public.signup_requests to anon;
grant select, insert, update on public.signup_requests to authenticated;
grant usage, select on sequence public.signup_requests_id_seq to anon;
grant usage, select on sequence public.signup_requests_id_seq to authenticated;

drop policy if exists "Anyone can submit signup requests" on public.signup_requests;
drop policy if exists "Super admins can read signup requests" on public.signup_requests;
drop policy if exists "Super admins can update signup requests" on public.signup_requests;

create policy "Anyone can submit signup requests"
on public.signup_requests
for insert
to anon, authenticated
with check (status = 'pending');

create policy "Super admins can read signup requests"
on public.signup_requests
for select
to authenticated
using (public.is_super_admin());

create policy "Super admins can update signup requests"
on public.signup_requests
for update
to authenticated
using (public.is_super_admin())
with check (public.is_super_admin());
